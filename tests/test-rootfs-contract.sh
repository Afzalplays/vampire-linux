#!/usr/bin/env bash
set -Eeuo pipefail
ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
for file in rootfs-overlay/usr/bin/vctl rootfs-overlay/usr/bin/vnetwork rootfs-overlay/usr/bin/vguard rootfs-overlay/usr/bin/vsettings rootfs-overlay/usr/bin/vdesktop rootfs-overlay/usr/bin/vmonitor rootfs-overlay/usr/bin/vinstall rootfs-overlay/usr/bin/vpm rootfs-overlay/usr/bin/vgraphical rootfs-overlay/usr/bin/vupdate rootfs-overlay/usr/bin/vsoftware rootfs-overlay/usr/bin/vssh rootfs-overlay/usr/bin/vfiles rootfs-overlay/usr/bin/vhardware rootfs-overlay/usr/bin/vstorage rootfs-overlay/usr/bin/vhealth rootfs-overlay/usr/bin/vlogs rootfs-overlay/usr/bin/vdiagnose rootfs-overlay/usr/bin/vfirewall rootfs-overlay/usr/bin/vpower rootfs-overlay/usr/bin/vsh rootfs-overlay/etc/vampire/shellrc rootfs-overlay/etc/vampire/services.d/firewall rootfs-overlay/etc/vpm/vpm.json rootfs-overlay/etc/vampire/update.json rootfs-overlay/etc/vampire/settings.defaults rootfs-overlay/etc/vampire/services.d/network rootfs-overlay/etc/profile.d/vampire.sh; do
  test -s "$ROOT/$file"
done
sh -n "$ROOT/rootfs-overlay/usr/bin/vctl"
sh -n "$ROOT/rootfs-overlay/etc/init.d/rcS"
"$ROOT/tests/test-service-manager.sh"
bash -n "$ROOT/rootfs-overlay/usr/bin/vnetwork"
bash -n "$ROOT/rootfs-overlay/usr/bin/vguard"
sh -n "$ROOT/rootfs-overlay/usr/bin/vsettings"
sh -n "$ROOT/rootfs-overlay/usr/bin/vdesktop"
sh -n "$ROOT/rootfs-overlay/usr/bin/vsh"
sh -n "$ROOT/rootfs-overlay/usr/bin/vmonitor"
sh -n "$ROOT/rootfs-overlay/usr/bin/vinstall"
sh -n "$ROOT/rootfs-overlay/usr/bin/vpm"
sh -n "$ROOT/rootfs-overlay/usr/bin/vgraphical"
sh -n "$ROOT/rootfs-overlay/usr/bin/vupdate"
sh -n "$ROOT/rootfs-overlay/usr/bin/vsoftware"
sh -n "$ROOT/rootfs-overlay/usr/bin/vssh"
sh -n "$ROOT/rootfs-overlay/usr/bin/vfiles"\nsh -n "$ROOT/rootfs-overlay/usr/bin/vpower"
for tool in vhardware vstorage vhealth vlogs vdiagnose vfirewall; do sh -n "$ROOT/rootfs-overlay/usr/bin/$tool"; done
sh -n "$ROOT/rootfs-overlay/etc/vampire/services.d/firewall"
sh -n "$ROOT/rootfs-overlay/etc/init.d/rcS"
sh -n "$ROOT/rootfs-overlay/etc/vampire/services.d/network"
grep -q 'BusyBox init' "$ROOT/rootfs-overlay/etc/vampire/os.conf"
grep -q 'production supervisor' "$ROOT/docs/VAMPIRE-INIT.md"
grep -q '/usr/bin/vctl start-all' "$ROOT/rootfs-overlay/etc/init.d/rcS"
grep -q 'services.enabled' "$ROOT/docs/VAMPIRE-INIT.md"
grep -q '/etc/init.d/rcK' "$ROOT/rootfs-overlay/etc/inittab"
grep -q 'stop-all' "$ROOT/rootfs-overlay/etc/init.d/rcK"
grep -q 'sync' "$ROOT/rootfs-overlay/etc/init.d/rcK"
grep -q 'VAMPIRE_SSH_PORT' "$ROOT/rootfs-overlay/usr/bin/vguard"
grep -q 'udhcpc -R -b -i' "$ROOT/rootfs-overlay/usr/bin/vnetwork"
grep -q 'udhcpc.script' "$ROOT/rootfs-overlay/usr/bin/vnetwork"
test -x "$ROOT/rootfs-overlay/usr/lib/vampire/udhcpc.script"
grep -q 'BR2_PACKAGE_FOOT=y' "$ROOT/build/vampire_defconfig"
test -s "$ROOT/rootfs-overlay/usr/bin/vampire-terminal"
test -s "$ROOT/rootfs-overlay/etc/xdg/weston/weston.ini"
test -x "$ROOT/rootfs-overlay/usr/bin/vampire-app"
test -x "$ROOT/rootfs-overlay/usr/bin/vhelp"
grep -qi "Command Reference" "$ROOT/rootfs-overlay/usr/bin/vhelp"
grep -q "vampire-app files" "$ROOT/rootfs-overlay/etc/xdg/weston/weston.ini"
grep -q "usr/bin/vampire-terminal" "$ROOT/build/build-live-iso.sh"
grep -q "usr/bin/vampire-app" "$ROOT/build/build-live-iso.sh"
grep -q "usr/bin/vhelp" "$ROOT/build/build-live-iso.sh"
grep -q "settings_apply.py" "$ROOT/build/build-live-iso.sh"
grep -q 'settings.conf' "$ROOT/rootfs-overlay/etc/init.d/rcS"
grep -q 'vsettings validate' "$ROOT/rootfs-overlay/etc/init.d/rcS"
grep -q '^BR2_PACKAGE_BASH=y$' "$ROOT/build/vampire_defconfig"
grep -q '^BR2_PACKAGE_BASH=y$' "$ROOT/build/vampire_server_defconfig"
grep -q '^BR2_PACKAGE_WESTON=y$' "$ROOT/build/vampire_defconfig"
grep -q 'BR2_PACKAGE_PYTHON3_SSL=y' "$ROOT/build/vampire_defconfig"
grep -q 'usr/lib/vampire/vpm' "$ROOT/build/build-live-iso.sh"
grep -q 'udevd --daemon' "$ROOT/rootfs-overlay/etc/init.d/rcS"
grep -q 'Open Vampire Shell' "$ROOT/rootfs-overlay/usr/bin/vdesktop"
grep -q '"$INSTALLER" system-check' "$ROOT/rootfs-overlay/usr/bin/vdesktop"
grep -q 'usr/bin/vsh' "$ROOT/build/build-live-iso.sh"
echo "Vampire rootfs contract checks passed."
